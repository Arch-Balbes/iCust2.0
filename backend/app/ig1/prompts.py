def dialogue_part(turns: list[dict[str, Any]]) -> str:
    return '\n'.join(f"[{t['turn_index']}] {'I' if t['speaker_role'] == 'interviewer' else 'R'}: {t['text']}"
                     for t in turns)


def chunk_view(head: list[dict[str, Any]], context: list[dict[str, Any]], target: list[dict[str, Any]]) -> str:
    parts = []
    if head:
        parts.append('НАЧАЛО ИНТЕРВЬЮ (контекст):\n' + dialogue_part(head))
    if context:
        parts.append('ПРЕДЫДУЩИЕ РЕПЛИКИ (контекст):\n' + dialogue_part(context))
    parts.append('ЦЕЛЕВЫЕ РЕПЛИКИ:\n' + dialogue_part(target))
    return '\n\n'.join(parts)


def user_3b_chunk(project: dict[str, Any], head: list[dict[str, Any]], context: list[dict[str, Any]], target: list[dict[str, Any]]) -> str:
    return f"План интервью:\n{dumps(project['plan'])}\n\nРасшифровка:\n{chunk_view(head, context, target)}"


